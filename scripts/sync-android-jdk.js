/**
 * Writes android/local.properties with:
 * - sdk.dir (Android SDK) from ANDROID_HOME, ANDROID_SDK_ROOT, ~/Library/Android/sdk, or android.sdk
 * - org.gradle.java.home from project-root jdk.home
 *
 * Usage: node scripts/sync-android-jdk.js
 */
const fs = require('fs');
const os = require('os');
const path = require('path');

const root = path.resolve(__dirname, '..');
const jdkFile = path.join(root, 'jdk.home');
const sdkFile = path.join(root, 'android.sdk');
const androidDir = path.join(root, 'android');
const localProps = path.join(androidDir, 'local.properties');

function firstPathLine(raw) {
  for (const line of raw.split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    return t.replace(/^["']|["']$/g, '');
  }
  return '';
}

function isValidSdkDir(dir) {
  if (!dir || !fs.existsSync(dir)) return false;
  return fs.existsSync(path.join(dir, 'platforms')) || fs.existsSync(path.join(dir, 'build-tools'));
}

function resolveAndroidSdk() {
  const fromEnv = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT;
  if (fromEnv && isValidSdkDir(fromEnv)) return path.resolve(fromEnv.trim());

  const macDefault = path.join(os.homedir(), 'Library/Android/sdk');
  if (isValidSdkDir(macDefault)) return macDefault;

  if (process.platform === 'win32' && process.env.LOCALAPPDATA) {
    const winSdk = path.join(process.env.LOCALAPPDATA, 'Android', 'Sdk');
    if (isValidSdkDir(winSdk)) return winSdk;
  }

  if (fs.existsSync(sdkFile)) {
    const p = firstPathLine(fs.readFileSync(sdkFile, 'utf8'));
    if (p && isValidSdkDir(p)) return path.resolve(p);
  }

  return null;
}

function main() {
  if (!fs.existsSync(androidDir)) {
    console.error('android/ folder not found. Run: npx expo prebuild --platform android');
    process.exit(1);
  }

  const sdk = resolveAndroidSdk();
  if (!sdk) {
    console.error(
      'Android SDK not found.\n' +
        '  Install Android Studio, open SDK Manager, then either:\n' +
        '    • export ANDROID_HOME="$HOME/Library/Android/sdk"   (macOS default)\n' +
        '    • or copy android.sdk.example → android.sdk and put your SDK path on one line\n' +
        '  Then run: npm run sync:jdk\n'
    );
    process.exit(1);
  }

  if (!fs.existsSync(jdkFile)) {
    console.error(
      'Missing jdk.home in project root.\n' +
        '  1. Copy jdk.home.example → jdk.home\n' +
        '  2. Put your JDK path on one line (folder that contains bin/java)\n' +
        '  3. Run: npm run sync:jdk\n'
    );
    process.exit(1);
  }

  const jdkHome = firstPathLine(fs.readFileSync(jdkFile, 'utf8'));
  if (!jdkHome) {
    console.error('jdk.home is empty. Add one line with your JDK path (see jdk.home.example).');
    process.exit(1);
  }

  const javaBin = path.join(jdkHome, 'bin', process.platform === 'win32' ? 'java.exe' : 'java');
  if (!fs.existsSync(javaBin)) {
    console.error(`Not a valid JDK home (no bin/java): ${jdkHome}`);
    process.exit(1);
  }

  const sdkLine = sdk.replace(/\\/g, '/');
  const jdkLine = jdkHome.replace(/\\/g, '/');

  const out = [
    '# Generated by npm run sync:jdk — do not commit if your paths are machine-specific',
    `sdk.dir=${sdkLine}`,
    `org.gradle.java.home=${jdkLine}`,
    '',
  ].join('\n');

  fs.writeFileSync(localProps, out, 'utf8');
  console.log(`Wrote sdk.dir → ${sdkLine}`);
  console.log(`Wrote org.gradle.java.home → ${jdkLine}`);
  console.log(`File: ${localProps}`);
}

main();
